internal fun DoomEngineCore.D_Display() {
    val y: Int
    val wipe: Boolean
    var redrawsbar: Boolean

    if (nodrawers)
        return  // for comparative timing / profiling

    redrawsbar = false

    // change the view size if needed
    if (setsizeneeded) {
        R_ExecuteSetViewSize()
        oldgamestate = -1  // force background redraw
        borderdrawcount = 3
    }

    // save the current screen if about to wipe
    if (gamestate != wipegamestate) {
        wipe = true
        wipe_StartScreen(0, 0, SCREENWIDTH, SCREENHEIGHT)
    } else
        wipe = false

    if (gamestate == GS_LEVEL && gametic != 0)
        HU_Erase()

    // do buffered drawing
    when (gamestate) {
        GS_LEVEL -> {
            if (gametic != 0) {
                if (automapactive)
                    AM_Drawer()
                if (wipe || (viewheight != 200 && fullscreen))
                    redrawsbar = true
                if (inhelpscreensstate && !inhelpscreens)
                    redrawsbar = true  // just put away the help screen
                ST_Drawer(viewheight == 200, redrawsbar)
                fullscreen = viewheight == 200
            }
        }

        GS_INTERMISSION ->
            WI_Drawer()

        GS_FINALE ->
            F_Drawer()

        GS_DEMOSCREEN ->
            D_PageDrawer()
    }

    // draw buffered stuff to screen
    I_UpdateNoBlit()

    // draw the view directly
    if (gamestate == GS_LEVEL && !automapactive && gametic != 0)
        R_RenderPlayerView(players[displayplayer])

    if (gamestate == GS_LEVEL && gametic != 0)
        HU_Drawer()

    // clean up border stuff
    if (gamestate != oldgamestate && gamestate != GS_LEVEL)
        I_SetPalette(W_CacheLumpName("PLAYPAL"))

    // see if the border needs to be initially drawn
    if (gamestate == GS_LEVEL && oldgamestate != GS_LEVEL) {
        viewactivestate = false  // view was not active
        R_FillBackScreen()  // draw the pattern into the back screen
    }

    // see if the border needs to be updated to the screen
    if (gamestate == GS_LEVEL && !automapactive && scaledviewwidth != 320) {
        if (menuactive || menuactivestate || !viewactivestate)
            borderdrawcount = 3
        if (borderdrawcount != 0) {
            R_DrawViewBorder()  // erase old menu stuff
            borderdrawcount--
        }
    }

    menuactivestate = menuactive
    viewactivestate = viewactive
    inhelpscreensstate = inhelpscreens
    oldgamestate = gamestate
    wipegamestate = gamestate

    // draw pause pic
    if (paused) {
        if (automapactive)
            y = 4
        else
            y = viewwindowy + 4
        V_DrawPatchDirect(viewwindowx + (scaledviewwidth - 68) / 2,
            y, 0, W_CacheLumpName("M_PAUSE"))
    }

    // menus go directly to the screen
    M_Drawer()  // menu is drawn even on top of everything
    // NetUpdate(); -- vanilla sent out any new accumulation here; the host
    // loop already calls TryRunTics/NetUpdate every frame.

    // normal update
    if (!wipe) {
        I_FinishUpdate()  // page flip or blit buffer
        return
    }

    // wipe update
    wipe_EndScreen(0, 0, SCREENWIDTH, SCREENHEIGHT)
    wipeActive = true
    wipestart = I_GetTime() - 1
}

/** One frame of the wipe (C: the do/while at the end of D_Display). */
internal fun DoomEngineCore.D_WipeStep() {
    val nowtime = I_GetTime()
    val tics = nowtime - wipestart
    if (tics == 0)
        return
    wipestart = nowtime
    val done = wipe_ScreenWipe(wipe_Melt, 0, 0, SCREENWIDTH, SCREENHEIGHT, tics)
    I_UpdateNoBlit()
    M_Drawer()  // menu is drawn even on top of wipes
    I_FinishUpdate()  // page flip or blit buffer
    if (done)
        wipeActive = false
}

//
//  D_DoomLoop -> D_DoomStep
//  Called by the host once per display frame (vanilla looped here forever).
//  Manages timing and IO,
//  calls all ?_Responder, ?_Ticker, and ?_Drawer,
//  calls I_GetTime, I_StartFrame, and I_StartTic
//
internal fun DoomEngineCore.D_DoomStep() {
    if (wipeActive) {
        D_WipeStep()
        return
    }

    // frame syncronous IO operations
    I_StartFrame()

    // process one or more tics
    if (singletics) {
        tickScheduler.advanceSingleTic()
    } else {
        tickScheduler.advanceDueTics()
    }

    S_UpdateSounds(players[consoleplayer].mo)  // move positional sounds

    // Update display, next frame, with current state.
    D_Display()
}

