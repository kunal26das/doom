//
// D_IdentifyVersion (C: IdentifyVersion)
// The C version checked availability of IWAD files by name; the host passes
// WAD images directly, so determine registered/commercial features by lump
// presence instead. Must be called after W_InitMultipleFiles.
//
internal fun DoomEngineCore.D_IdentifyVersion() {
    if (W_CheckNumForName("MAP01") != -1) {
        // Commercial. (TNT/Plutonia can't be told apart without filenames.)
        gamemission = doom2
        gamemode = commercial
    } else if (W_CheckNumForName("E4M1") != -1) {
        // Retail.
        gamemission = doom
        gamemode = retail
    } else if (W_CheckNumForName("E2M1") != -1 || W_CheckNumForName("E3M1") != -1) {
        // Registered.
        gamemission = doom
        gamemode = registered
    } else if (W_CheckNumForName("E1M1") != -1) {
        // Shareware.
        gamemission = doom
        gamemode = shareware
    } else {
        println("Game mode indeterminate.")
        gamemode = indetermined
        // We don't abort. Let's see what the PWAD contains.
    }
}

//
// D_DoomMain
// Calls all startup code, parses command line options.
// The host supplies the WAD images (IWAD first, then PWADs) and the args;
// after it returns, the host drives the game by calling D_DoomStep()
// once per display frame (C: ended in the never-returning D_DoomLoop).
//
internal fun DoomEngineCore.D_DoomMain(wads: List<ByteArray>, args: List<String>) {
    var p: Int

    myargv = listOf("doom") + args

    modifiedgame = false

    nomonsters = M_CheckParm("-nomonsters") != 0
    respawnparm = M_CheckParm("-respawn") != 0
    fastparm = M_CheckParm("-fast") != 0
    devparm = M_CheckParm("-devparm") != 0
    if (M_CheckParm("-altdeath") != 0)
        deathmatch = 2
    else if (M_CheckParm("-deathmatch") != 0)
        deathmatch = 1

    println("W_Init: Init WADfiles.")
    W_InitMultipleFiles(wads)

    D_IdentifyVersion()
    M_ValidateArguments(gamemode == commercial)
    // language stays english (no doom2f.wad handling)

    val title: String
    when (gamemode) {
        retail ->
            title = "                         " +
                "The Ultimate DOOM Startup v${VERSION / 100}.${VERSION % 100}" +
                "                           "
        shareware ->
            title = "                            " +
                "DOOM Shareware Startup v${VERSION / 100}.${VERSION % 100}" +
                "                           "
        registered ->
            title = "                            " +
                "DOOM Registered Startup v${VERSION / 100}.${VERSION % 100}" +
                "                           "
        commercial ->
            title = "                         " +
                "DOOM 2: Hell on Earth v${VERSION / 100}.${VERSION % 100}" +
                "                           "
        else ->
            title = "                     " +
                "Public DOOM - v${VERSION / 100}.${VERSION % 100}" +
                "                           "
    }

    println(title)

    if (devparm)
        print(D_DEVSTR)

    // turbo option
    p = M_CheckParm("-turbo")
    if (p != 0) {
        var scale = 200

        if (p < myargc - 1 && !myargv[p + 1].startsWith('-'))
            scale = myargv[p + 1].toInt()
        if (scale < 10)
            scale = 10
        if (scale > 400)
            scale = 400
        println("turbo scale: $scale%")
        forwardmove[0] = forwardmove[0] * scale / 100
        forwardmove[1] = forwardmove[1] * scale / 100
        sidemove[0] = sidemove[0] * scale / 100
        sidemove[1] = sidemove[1] * scale / 100
    }

    // C added PWADs given with -file to the wad list here; the host passes
    // extra WAD images in `wads` instead -- treat those as homebrew levels.
    if (wads.size > 1)
        modifiedgame = true  // homebrew levels

    p = M_CheckParm("-playdemo")

    if (p == 0)
        p = M_CheckParm("-timedemo")

    if (p != 0 && p < myargc - 1)
        println("Playing demo ${myargv[p + 1]}.lmp.")

    // get skill / episode / map from parms
    startskill = sk_medium
    startepisode = 1
    startmap = 1
    autostart = false

    p = M_CheckParm("-skill")
    if (p != 0 && p < myargc - 1) {
        startskill = myargv[p + 1].toInt() - 1
        autostart = true
    }

    p = M_CheckParm("-episode")
    if (p != 0 && p < myargc - 1) {
        startepisode = myargv[p + 1].toInt()
        startmap = 1
        autostart = true
    }

    p = M_CheckParm("-timer")
    if (p != 0 && p < myargc - 1 && deathmatch != 0) {
        val time = myargv[p + 1].toIntOrNull() ?: 0
        print("Levels will end after $time minute")
        if (time > 1)
            print("s")
        println(".")
    }

    p = M_CheckParm("-avg")
    if (p != 0 && p < myargc - 1 && deathmatch != 0)
        println("Austin Virtual Gaming: Levels will end after 20 minutes")

    p = M_CheckParm("-warp")
    if (p != 0 && p < myargc - 1) {
        if (gamemode == commercial)
            startmap = myargv[p + 1].toIntOrNull() ?: 0
        else {
            startepisode = myargv[p + 1].toInt()
            startmap = myargv[p + 2].toInt()
        }
        autostart = true
    }

    // Check for -file in shareware
    if (modifiedgame) {
        // These are the lumps that will be checked in IWAD,
        // if any one is not present, execution will be aborted.
        val name = arrayOf(
            "e2m1", "e2m2", "e2m3", "e2m4", "e2m5", "e2m6", "e2m7", "e2m8", "e2m9",
            "e3m1", "e3m3", "e3m3", "e3m4", "e3m5", "e3m6", "e3m7", "e3m8", "e3m9",
            "dphoof", "bfgga0", "heada1", "cybra1", "spida1d1"
        )

        if (gamemode == shareware)
            I_Error("\nYou cannot -file with the shareware version. Register!")

        // Check for fake IWAD with right name,
        // but w/o all the lumps of the registered version.
        if (gamemode == registered)
            for (i in 0 until 23)
                if (W_CheckNumForName(name[i]) < 0)
                    I_Error("\nThis is not the registered version.")
    }

    // Iff additonal PWAD files are used, print modified banner
    if (modifiedgame) {
        println(
            "===========================================================================\n" +
            "ATTENTION:  This version of DOOM has been modified.  If you would like to\n" +
            "get a copy of the original game, call 1-800-IDGAMES or see the readme file.\n" +
            "        You will not receive technical support for modified games.\n" +
            "                      press enter to continue\n" +
            "==========================================================================="
        )
    }

    // Check and print which version is executed.
    when (gamemode) {
        shareware, indetermined ->
            println(
                "===========================================================================\n" +
                "                                Shareware!\n" +
                "==========================================================================="
            )
        registered, retail, commercial ->
            println(
                "===========================================================================\n" +
                "                 Commercial product - do not distribute!\n" +
                "         Please report software piracy to the SPA: 1-800-388-PIR8\n" +
                "==========================================================================="
            )
        else -> {
            // Ouch.
        }
    }

    println("V_Init: allocate screens.")
    V_Init()

    println("M_LoadDefaults: Load system defaults.")
    M_LoadDefaults()  // load before initing other systems

    println("M_Init: Init miscellaneous info.")
    M_Init()

    print("R_Init: Init DOOM refresh daemon - ")
    R_Init()

    // Register A_* codepointers and resolve state action names
    // (replaces C info.c's static action-function table).
    P_RegisterEnemyActions()
    P_RegisterPsprActions()
    InfoResolveActions()

    println("\nP_Init: Init Playloop state.")
    P_Init()

    println("I_Init: Setting up machine state.")
    I_InitGraphics()

    println("D_CheckNetGame: Checking network game status.")
    // D_CheckNetGame: networking not ported -- single local player.
    netgame = false
    consoleplayer = 0
    displayplayer = 0
    playeringame[0] = true
    ticdup = 1

    println("startskill $startskill  deathmatch: $deathmatch  startmap: $startmap  startepisode: $startepisode")

    println("S_Init: Setting up sound.")
    S_Init(snd_SfxVolume /* *8 */, snd_MusicVolume /* *8 */)

    println("HU_Init: Setting up heads up display.")
    HU_Init()

    println("ST_Init: Init status bar.")
    ST_Init()

    // start the apropriate game based on parms
    p = M_CheckParm("-record")

    if (p != 0 && p < myargc - 1) {
        G_RecordDemo(myargv[p + 1])
        autostart = true
    }

    p = M_CheckParm("-playdemo")
    if (p != 0 && p < myargc - 1) {
        singledemo = true  // quit after one demo
        G_DeferedPlayDemo(myargv[p + 1])
        if (demorecording)
            G_BeginRecording()  // C: top of D_DoomLoop
        return  // C: D_DoomLoop() -- host drives D_DoomStep() from here on
    }

    p = M_CheckParm("-timedemo")
    if (p != 0 && p < myargc - 1) {
        G_TimeDemo(myargv[p + 1])
        if (demorecording)
            G_BeginRecording()  // C: top of D_DoomLoop
        return  // C: D_DoomLoop() -- host drives D_DoomStep() from here on
    }

    p = M_CheckParm("-loadgame")
    if (p != 0 && p < myargc - 1) {
        G_LoadGame("$SAVEGAMENAME${myargv[p + 1].toInt()}.dsg")
    }

    if (gameaction != ga_loadgame) {
        if (autostart || netgame)
            G_InitNew(startskill, startepisode, startmap)
        else
            D_StartTitle()  // start up intro loop
    }

    if (demorecording)
        G_BeginRecording()  // C: top of D_DoomLoop

    // C: D_DoomLoop() -- never returns; here the host drives D_DoomStep().
}
