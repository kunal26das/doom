//
// EVENT HANDLING
//
// Events are asynchronous inputs generally generated by the game user.
// Events can be discarded if no responder claims them
//
internal const val MAXEVENTS = 64  // d_event.h

internal fun DoomEngineCore.D_PostEvent(ev: event_t) { inputQueue.stage(ev) }

internal fun DoomEngineCore.D_ProcessEvents() {
    // The commercial store demo intentionally ignores player input.
    if (gamemode == commercial && W_CheckNumForName("map01") < 0) {
        inputQueue.clearPending()
        return
    }
    inputQueue.dispatch { event ->
        if (!M_Responder(event)) G_Responder(event)
    }
}

