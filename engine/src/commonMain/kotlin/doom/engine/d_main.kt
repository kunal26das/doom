}

//
// D_AdvanceDemo
// Called after each demo or intro demosequence finishes
//
internal fun DoomEngineCore.D_AdvanceDemo() {
    advancedemo = true
}

//
// This cycles through the demo sequences.
// FIXME - version dependend demo numbers?
//
internal fun DoomEngineCore.D_DoAdvanceDemo() {
    players[consoleplayer].playerstate = PST_LIVE  // not reborn
    advancedemo = false
    usergame = false  // no save / end game here
    paused = false
    gameaction = ga_nothing

    if (gamemode == retail)
        demosequence = (demosequence + 1) % 7
    else
        demosequence = (demosequence + 1) % 6

    when (demosequence) {
        0 -> {
            if (gamemode == commercial)
                pagetic = 35 * 11
            else
                pagetic = 170
            gamestate = GS_DEMOSCREEN
            pagename = "TITLEPIC"
            if (gamemode == commercial)
                S_StartMusic(mus_dm2ttl)
            else
                S_StartMusic(mus_intro)
        }
        1 -> G_DeferedPlayDemo("demo1")
        2 -> {
            pagetic = 200
            gamestate = GS_DEMOSCREEN
            pagename = "CREDIT"
        }
        3 -> G_DeferedPlayDemo("demo2")
        4 -> {
            gamestate = GS_DEMOSCREEN
            if (gamemode == commercial) {
                pagetic = 35 * 11
                pagename = "TITLEPIC"
                S_StartMusic(mus_dm2ttl)
            } else {
                pagetic = 200

                if (gamemode == retail)
                    pagename = "CREDIT"
                else
                    pagename = "HELP2"
            }
        }
        5 -> G_DeferedPlayDemo("demo3")
        // THE DEFINITIVE DOOM Special Edition demo
        6 -> G_DeferedPlayDemo("demo4")
    }
}

